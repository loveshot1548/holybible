  useEffect(() => setLocal('ytc_pre_eval_v1', preEval), [preEval]);
  useEffect(() => setLocal('ytc_post_eval_v1', postEval), [postEval]);
  useEffect(() => setLocal('ytc_roleplay_rubric_v1', roleplayScores), [roleplayScores]);

